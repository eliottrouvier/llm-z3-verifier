"""
SMT-LIB v2 Parser & Grammar Sanitizer.
Parses, validates, and cleans raw SMT-LIB v2 script strings generated by LLMs.
Ensures balanced syntax, valid logic dialect declarations, and AST safety.
"""

from __future__ import annotations
import re
from dataclasses import dataclass
from typing import Any, Dict, List, Optional, Set
import z3


@dataclass
class SMTLibScript:
    raw_text: str
    logic: Optional[str] = None
    declared_constants: Dict[str, str] = None  # name -> sort (e.g. 'Int', 'Real')
    assertions: List[str] = None
    is_valid_syntax: bool = True
    syntax_error: Optional[str] = None


class SMTLibParser:
    """Parser and validator for SMT-LIB v2 strings."""

    SUPPORTED_LOGICS = {
        "QF_LIA", "QF_NIA", "QF_LRA", "QF_NRA", "QF_BV", "ALL", "QF_AUFBV"
    }

    def sanitize(self, raw_script: str) -> str:
        """Strips markdown code blocks, trailing text, and redundant comments."""
        clean = raw_script.strip()
        if clean.startswith("```smt2") or clean.startswith("```lisp") or clean.startswith("```smt"):
            clean = clean.split("\n", 1)[1]
        elif clean.startswith("```"):
            clean = clean.split("\n", 1)[1]

        if clean.endswith("```"):
            clean = clean.rsplit("\n", 1)[0]

        # Normalize line endings
        lines = []
        for line in clean.splitlines():
            # Strip inline comment
            stripped = line.split(";", 1)[0].rstrip()
            if stripped:
                lines.append(stripped)
        return "\n".join(lines)

    def validate_parentheses(self, text: str) -> bool:
        """Checks if S-expression parentheses are strictly balanced."""
        depth = 0
        in_string = False
        escape = False

        for char in text:
            if char == '"' and not escape:
                in_string = not in_string
            elif not in_string:
                if char == '(':
                    depth += 1
                elif char == ')':
                    depth -= 1
                    if depth < 0:
                        return False
            escape = (char == '\\' and not escape)

        return depth == 0

    def parse(self, raw_script: str) -> SMTLibScript:
        """
        Parses SMT-LIB v2 script, extracts logic, declared constants, and assertions.
        Validates through Z3 parser.
        """
        sanitized = self.sanitize(raw_script)

        if not self.validate_parentheses(sanitized):
            return SMTLibScript(
                raw_text=sanitized,
                is_valid_syntax=False,
                syntax_error="Unbalanced parentheses in S-expression"
            )

        declared_constants = {}
        assertions = []
        logic = None

        # Extract set-logic
        logic_match = re.search(r"\(set-logic\s+([A-Za-z_]+)\)", sanitized)
        if logic_match:
            logic = logic_match.group(1)

        # Extract declare-const
        for match in re.finditer(r"\(declare-const\s+([A-Za-z0-9_]+)\s+([A-Za-z0-9_]+)\)", sanitized):
            name, sort = match.group(1), match.group(2)
            declared_constants[name] = sort

        # Extract assert statements
        # Matches balanced (assert ...)
        assert_pattern = re.findall(r"\(assert\s+.*?\n?\)", sanitized, re.DOTALL)
        for a in assert_pattern:
            assertions.append(a.strip())

        # Ensure (check-sat) is present or append it
        if "(check-sat)" not in sanitized:
            sanitized += "\n(check-sat)"

        # Validate with Z3 parser directly
        try:
            # z3.parse_smt2_string returns AST vector
            _ = z3.parse_smt2_string(sanitized)
            return SMTLibScript(
                raw_text=sanitized,
                logic=logic,
                declared_constants=declared_constants,
                assertions=assertions,
                is_valid_syntax=True,
                syntax_error=None
            )
        except Exception as e:
            return SMTLibScript(
                raw_text=sanitized,
                logic=logic,
                declared_constants=declared_constants,
                assertions=assertions,
                is_valid_syntax=False,
                syntax_error=str(e)
            )
