#!/usr/bin/env python3
"""
Example 13: Minimal Unsatisfiable Subformula (MUS) & Redundant Hypothesis Pruning.
Demonstrates:
1. An over-specified set of mathematical hypotheses generated by an LLM.
2. Z3 boolean-tracked assertions to identify the raw Unsat Core.
3. Deletion-filter algorithm to extract the irreducible Minimal Unsat Subformula (MUS).
4. Pruning redundant distractor axioms.
"""

import sys
import os
sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), "..")))

from src.unsat_core import UnsatCoreEngine


def main():
    print("=" * 75)
    print("Example 13: SMT Unsat Core & Minimal Axiom Extraction (MUS)")
    print("=" * 75)

    engine = UnsatCoreEngine()

    # Over-specified hypothesis pool from LLM:
    hypotheses = {
        "H_order_1": "x > 100",
        "H_parity": "y % 2 == 0",         # Distractor / redundant
        "H_order_2": "x < 50",
        "H_positivity": "z >= 0",         # Distractor / redundant
        "H_algebra": "w == 2 * y + 1",    # Distractor / redundant
        "H_bound": "x != 75"              # Redundant given H_order_1
    }

    print("Initial Hypothesis Pool (6 premises):")
    for k, v in hypotheses.items():
        print(f"  [{k}] : {v}")

    print("\n-> Running Tracked Literal Resolution & Deletion MUS Filter...")
    res = engine.extract_unsat_core(
        var_specs={"x": "Int", "y": "Int", "z": "Int", "w": "Int"},
        hypotheses=hypotheses
    )

    print(f"\nUnsat Verified:       {res.is_unsat}")
    print(f"Raw Z3 Core:          {res.raw_unsat_core}")
    print(f"Irreducible MUS Core: {res.minimal_unsat_core}")
    print(f"Pruned Distractors:   {res.redundant_hypotheses}")
    print(f"Hypothesis Reduction: {res.reduction_ratio * 100:.1f}%\n")
    print(f"Mathematical Diagnosis: {res.explanation}")
    print("=" * 75)


if __name__ == "__main__":
    main()
